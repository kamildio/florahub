// Production auth handlers with isolated SQLite and a captured SMTP message.
import assert from 'node:assert/strict';
import {register} from 'node:module';
register('./fixtures/acceptance-loader.mjs',import.meta.url);
const {env}=await import('./fixtures/acceptance-runtime.mjs');
const {GET,POST}=await import('../app/api/platform/[...path]/route.js');
const messages=[],deletionNotices=[];
Object.assign(env,{TEST_MODE:'false',EMAIL_AUTH_ENABLED:'true',SEND_DELETION_NOTICE:async job=>deletionNotices.push(job),EMAIL_CONFIGURED:true,EMAIL_CODE_SECRET:'test-only-smtp-key'.repeat(3),SEND_VERIFICATION_EMAIL:async message=>messages.push(message),REGISTRATION_ENABLED:'true',LEGAL_APPROVED_VERSION:'launch-v3'});
await env.DB.prepare('ALTER TABLE accounts ADD COLUMN email TEXT').run();
await env.DB.prepare('CREATE UNIQUE INDEX accounts_email ON accounts(email)').run();
const origin='https://www.maxiflora.test';
const cookie=response=>response.headers.get('set-cookie').split(';')[0];
const post=(path,body,session='')=>POST(new Request(origin+'/api/platform/'+path,{method:'POST',headers:{origin,'content-type':'application/json',cookie:session},body:JSON.stringify(body)}));
const state=async(session='')=>(await GET(new Request(origin+'/api/platform/state',{headers:{cookie:session}}))).json();
const signup={companyType:'IP',channel:'email',purpose:'register',phone:'+77060000123',email:'Buyer@Example.test',name:'Synthetic Buyer',password:'test-password',passwordConfirmation:'test-password',agreement:true,privacy:true};
async function send(details){
 const response=await post('auth-code-send',{...details,operationId:crypto.randomUUID()});
 assert.equal(response.status,200);
 return {id:(await response.json()).id,browser:cookie(response)};
}
const initial=await state();
assert.equal(initial.phoneAuth.email,true);
assert.equal(initial.phoneAuth.registration,true);
assert.equal(initial.phoneAuth.channels.telegram,false);
assert.equal(initial.telegram.configured,false);
assert.equal((await post('auth-code-send',{...signup,channel:'telegram'})).status,503);
const registration=await send(signup);
assert.equal(messages[0].to,'buyer@example.test');
const checkSignup={...signup,id:registration.id,code:messages[0].code};
assert.equal((await post('auth-code-verify',checkSignup)).status,422);
const registered=await post('auth-code-verify',checkSignup,registration.browser);
assert.equal(registered.status,200);
assert.equal((await state(cookie(registered))).authenticated,true);
const account=await env.DB.prepare('SELECT * FROM accounts WHERE email=?').bind('buyer@example.test').first();
const profile=JSON.parse(account.profile);
assert.equal(profile.verificationMethod,'email');
assert.equal(profile.phoneVerified,false);
assert.equal((await post('auth-code-verify',checkSignup,registration.browser)).status,422);
assert.equal((await post('login',{phone:signup.phone,password:signup.password})).status,200);
const missing=await send({channel:'email',purpose:'login',email:'missing@example.test'});
assert.ok(missing.id);
assert.equal(messages.length,1);
// Advance the send cooldown without invalidating the test account or session.
const {mutateState}=await import('../lib/maxiflora/store.mjs');
await mutateState(env.DB,'live',s=>{s.authChallenges.find(x=>x.id===registration.id).resendAt=0;});
const login={channel:'email',purpose:'login',email:signup.email};
const issued=await send(login);
assert.equal(messages.length,2);
assert.equal(messages[1].purpose,'login');
const checked={...login,id:issued.id,code:messages[1].code};
assert.equal((await post('auth-code-verify',checked)).status,422);
const signedIn=await post('auth-code-verify',checked,issued.browser);
assert.equal(signedIn.status,200);
assert.equal((await state(cookie(signedIn))).authenticated,true);
assert.equal((await post('auth-code-verify',checked,issued.browser)).status,422);
await mutateState(env.DB,'live',s=>{s.authChallenges.find(x=>x.id===issued.id).resendAt=0;});
const recovery={...login,purpose:'reset-password'};
const reset=await send(recovery);
const changed=await post('auth-code-verify',{...recovery,id:reset.id,code:messages[2].code,password:'replacement-password'},reset.browser);
assert.equal(changed.status,200);
assert.equal((await state(cookie(signedIn))).authenticated,false);
assert.equal((await post('login',{phone:signup.phone,password:'replacement-password'})).status,200);
console.log('Email signup, login, recovery, browser binding, single use, private account lookup and password fallback passed.');

const deletionBody={action:'privacy-delete-request',operationId:crypto.randomUUID(),reason:'Synthetic deletion request'};
const deletion=await post('action',deletionBody,cookie(changed));
assert.equal(deletion.status,200);
const ticket=await deletion.json();assert.ok(Number.isSafeInteger(ticket.number));
const repeated=await post('action',deletionBody,cookie(changed));assert.equal(repeated.status,200);assert.equal((await repeated.json()).id,ticket.id);
assert.equal(deletionNotices.length,1);
assert.equal((await state(cookie(changed))).authenticated,true);
assert.equal((await env.DB.prepare('SELECT COUNT(*) n FROM accounts').first()).n,1);
console.log('Deletion request is private, persisted, repeat-safe and emits one mocked admin email without removing the account.');
